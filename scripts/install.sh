#!/usr/bin/env bash
# tonearm install script — bare-metal bootstrap (#52, #132)
#
# Creates a venv, installs deps, bootstraps the profile dir (0700, the
# sensitive artifact), and checks for Chrome/Chromium. Safe to re-run.
#
# Usage:
#   bash scripts/install.sh [--dir DIR] [--venv VENV] [--no-deps] [--systemd]
#
#   --dir DIR      install root (default: $HOME/tonearm)
#   --venv VENV    venv path (default: $DIR/.venv)
#   --no-deps      skip pip install (venv/profile still ensured)
#   --systemd      also emit a systemd user unit next to the install
#
# Non-root by default. The Chrome profile holds your Apple Music session —
# keep it private and backed up.

set -euo pipefail

DIR="${TONEARM_INSTALL_DIR:-$HOME/tonearm}"
VENV=""
NO_DEPS=0
EMIT_SYSTEMD=0

while [ $# -gt 0 ]; do
  case "$1" in
    --dir) DIR="$2"; shift 2 ;;
    --venv) VENV="$2"; shift 2 ;;
    --no-deps) NO_DEPS=1; shift ;;
    --systemd) EMIT_SYSTEMD=1; shift ;;
    -h|--help)
      sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

VENV="${VENV:-$DIR/.venv}"
PROFILE="${TONEARM_PROFILE:-$HOME/.config/tonearm/chrome-profile}"
DATA="${TONEARM_STORE_PATH:-$HOME/.local/share/tonearm}"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"

say() { printf '[tonearm-install] %s\n' "$*"; }
warn() { printf '[tonearm-install] WARN: %s\n' "$*" >&2; }

if [ "$(id -u)" -eq 0 ]; then
  warn "running as root — non-root is recommended (the profile is a sensitive artifact)"
fi

command -v python3 >/dev/null 2>&1 || { echo "python3 is required" >&2; exit 1; }
PYVER=$(python3 -c 'import sys; print("%d.%d"%sys.version_info[:2])')
say "python3 $PYVER"

say "install root: $DIR"
say "venv:         $VENV"
say "profile dir:  $PROFILE (0700)"
say "data dir:     $DATA"

mkdir -p "$DIR" "$DATA"
mkdir -p "$PROFILE"
chmod 700 "$PROFILE"

if [ ! -x "$VENV/bin/python" ]; then
  say "creating venv"
  python3 -m venv "$VENV"
else
  say "venv exists"
fi

if [ "$NO_DEPS" -eq 0 ]; then
  if [ -f "$DIR/requirements.txt" ]; then
    say "installing dependencies from $DIR/requirements.txt"
    "$VENV/bin/pip" install --upgrade pip >/dev/null
    "$VENV/bin/pip" install -r "$DIR/requirements.txt"
  else
    warn "no requirements.txt at $DIR/requirements.txt — clone the repo there or run with --no-deps"
  fi
else
  say "skipping dependency install (--no-deps)"
fi

# Chrome/Chromium check (tonearm drives a real browser session)
CHROME=""
for c in google-chrome google-chrome-stable chromium chromium-browser; do
  if command -v "$c" >/dev/null 2>&1; then CHROME="$c"; break; fi
done
if [ -n "$CHROME" ]; then
  say "browser: $CHROME"
else
  warn "no Chrome/Chromium found on PATH — install google-chrome or chromium (see Dockerfile for the CI recipe)"
fi

# Optional: ffmpeg/pulse/Xvfb for audio streaming
for tool in ffmpeg pulseaudio Xvfb; do
  command -v "$tool" >/dev/null 2>&1 || warn "$tool not found (needed only for TONEARM_AUDIO=1)"
done

if [ "$EMIT_SYSTEMD" -eq 1 ]; then
  mkdir -p "$UNIT_DIR"
  UNIT="$UNIT_DIR/tonearm.service"
  say "writing systemd user unit: $UNIT"
  cat > "$UNIT" <<UNIT
# Generated by tonearm install script. Review before enabling.
# Encodes ops lessons: proper detachment, XDG_RUNTIME_DIR/pulse for audio,
# non-root, Chrome profile as the sensitive artifact.
[Unit]
Description=tonearm — self-hosted Apple Music API
After=network-online.target sound.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$DIR
ExecStart=$VENV/bin/python -m tonearm
Restart=on-failure
RestartSec=5
# Required for user pulse/audio when TONEARM_AUDIO=1
Environment=XDG_RUNTIME_DIR=%t
Environment=TONEARM_PROFILE=$PROFILE
# Set TONEARM_API_KEY before exposing beyond localhost.
# Environment=TONEARM_API_KEY=change-me

[Install]
WantedBy=default.target
UNIT
  say "enable with: systemctl --user daemon-reload && systemctl --user enable --now tonearm"
  say "for lingered boot: loginctl enable-linger $(id -un)"
fi

say "done."
say "next: sign in once with a visible browser:"
say "  TONEARM_PROFILE=$PROFILE $VENV/bin/python -m tonearm.login"
say "then serve: $VENV/bin/python -m tonearm"
